/// Returns the row accessors for the columns of an imposm3 table.
pub fn parse_table_fields(table: &Imposm3Table) -> anyhow::Result<Vec<OsmTableField>> {
    let mut result = Vec::new();
    let relation_member = table.r#type == "relation_member";
    for col in &table.columns {
        if relation_member && col.from_member {
            // layers process relation info that they need manually
            continue;
        }
        let key = || col.key.clone().with_context(|| format!("missing key for column {col:?}"));
        let field = |rust_type, extract_code: String| OsmTableField { rust_type, name: col.name.clone(), extract_code };
        match col.r#type.as_str() {
            // do nothing - already on source feature
            "id" | "validated_geometry" | "area" | "hstore_tags" | "geometry" => {}
            "member_id" | "member_role" | "member_type" | "member_index" => {}
            "mapping_key" => result.push(field(FieldType::MappingKey, "self.mapping_key".into())),
            "mapping_value" => {
                result.push(field(FieldType::String, "tag_string(self.source, self.mapping_key)".into()))
            }
            "string" => result.push(field(FieldType::String, format!("tag_string(self.source, {:?})", key()?))),
            "bool" => result.push(field(FieldType::Bool, format!("self.source.get_boolean({:?})", key()?))),
            "integer" => result.push(field(FieldType::Long, format!("self.source.get_long({:?})", key()?))),
            "wayzorder" => result.push(field(FieldType::Int, "self.source.get_way_zorder()".into())),
            "direction" => result.push(field(FieldType::Int, format!("self.source.get_direction({:?})", key()?))),
            other => bail!("Unhandled column: {other}"),
        }
    }
    result.push(OsmTableField {
        rust_type: FieldType::Source,
        name: "source".into(),
        extract_code: "self.source".into(),
    });
    Ok(result)
}

