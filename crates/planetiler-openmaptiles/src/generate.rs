/// Guava `CaseFormat.LOWER_UNDERSCORE.to(UPPER_CAMEL, name.replace(":", "__"))`.
pub fn lower_underscore_to_upper_camel(name: &str) -> String {
    name.replace(':', "__")
        .split('_')
        .filter(|p| !p.is_empty())
        .map(|p| {
            let mut chars = p.chars();
            match chars.next() {
                Some(first) => first.to_ascii_uppercase().to_string() + &chars.as_str().to_ascii_lowercase(),
                None => String::new(),
            }
        })
        .collect()
}

const RUST_KEYWORDS: &[&str] = &[
    "as", "break", "const", "continue", "crate", "else", "enum", "extern", "false", "fn", "for", "if", "impl", "in",
    "let", "loop", "match", "mod", "move", "mut", "pub", "ref", "return", "self", "Self", "static", "struct", "super",
    "trait", "true", "type", "unsafe", "use", "where", "while", "async", "await", "dyn", "abstract", "become", "box",
    "do", "final", "macro", "override", "priv", "typeof", "unsized", "virtual", "yield", "try", "gen",
];

/// A snake_case rust identifier for `name` (`:` -> `__`, keywords are escaped as raw identifiers).
pub fn snake_ident(name: &str) -> String {
    let ident = name.replace(':', "__");
    if RUST_KEYWORDS.contains(&ident.as_str()) { format!("r#{ident}") } else { ident }
}

/// A SCREAMING_SNAKE constant name for `name`.
pub fn const_ident(name: &str) -> String {
    name.to_uppercase()
        .replace(':', "__")
        .chars()
        .map(|c| if c.is_ascii_alphanumeric() || c == '_' { c } else { '_' })
        .collect()
}

/// Rust string literal for `s`.
pub fn quote(s: &str) -> String {
    format!("{s:?}")
}

/// Returns rust code that will recreate an [`Expression`] identical to `expression` (using the functions in
/// `planetiler_core::expression::expression`).
pub fn generate_rust_code(expression: &Expression) -> anyhow::Result<String> {
    fn list(items: &[Expression]) -> anyhow::Result<String> {
        Ok(items.iter().map(generate_rust_code).collect::<anyhow::Result<Vec<_>>>()?.join(", "))
    }
    Ok(match expression {
        Expression::Constant(true) => "Expression::TRUE".to_string(),
        Expression::Constant(false) => "Expression::FALSE".to_string(),
        Expression::And(children) => format!("and([{}])", list(children)?),
        Expression::Or(children) => format!("or([{}])", list(children)?),
        Expression::Not(child) => format!("not({})", generate_rust_code(child)?),
        Expression::MatchAny(any) => {
            if any.getter != Getter::Data(DataType::GetTag) {
                bail!("Code generation only supported for default getTag");
            }
            let field = any.field.as_deref().context("Code generation requires a field")?;
            let values = any
                .values
                .iter()
                .map(|v| match v {
                    Value::String(s) => Ok(quote(s)),
                    other => bail!("Code generation only supported for string values, found: {other:?}"),
                })
                .collect::<anyhow::Result<Vec<_>>>()?;
            format!("match_any({}, [{}])", quote(field), values.join(", "))
        }
        Expression::MatchField(field) => format!("match_field({})", quote(field)),
        Expression::MatchType(t) => format!("match_type({})", quote(t)),
        Expression::MatchSource(s) => format!("match_source({})", quote(s)),
        Expression::MatchSourceLayer(l) => format!("match_source_layer({})", quote(l)),
        Expression::Custom(c) => bail!("Code generation not supported for custom expression {c:?}"),
    })
}

/// Returns rust code that will recreate a [`MultiExpression`] identical to `mapping`.
fn generate_multi_expression_code(mapping: &MultiExpression<String>) -> anyhow::Result<String> {
    let entries = mapping
        .expressions
        .iter()
        .map(|e| Ok(format!("entry({}, {})", quote(&e.result), generate_rust_code(&e.expression)?)))
        .collect::<anyhow::Result<Vec<_>>>()?;
    Ok(format!("MultiExpression::of(vec![{}])", entries.join(", ")))
}

/// Renders `text` as `///` (or `//!` with `inner`) doc comment lines indented by `indent`.
fn doc_comment(text: &str, indent: &str, inner: bool) -> String {
    let marker = if inner { "//!" } else { "///" };
    let mut out = String::new();
    // collapse runs of blank lines to a single paragraph break, strip trailing whitespace
    let mut last_blank = true;
    for line in text.trim().lines() {
        let line = line.trim_end();
        let line = line.trim_start();
        if line.is_empty() {
            if !last_blank {
                let _ = writeln!(out, "{indent}{marker}");
            }
            last_blank = true;
        } else {
            let _ = writeln!(out, "{indent}{marker} {line}");
            last_blank = false;
        }
    }
    out
}

fn field_description(value: &Yaml) -> String {
    match value {
        Yaml::String(s) => s.clone(),
        other => get_str(other, "description").unwrap_or_default(),
    }
}

