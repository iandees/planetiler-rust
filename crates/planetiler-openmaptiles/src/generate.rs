    /// The checked-in generated code must match what the generator produces from the vendored schema.
    #[test]
    fn test_generated_code_is_up_to_date() {
        let dir = Path::new(env!("CARGO_MANIFEST_DIR"));
        let tag = std::fs::read_to_string(dir.join("schema/REF")).unwrap();
        let generated = generate(&dir.join("schema"), tag.trim()).unwrap();
        // the checked-in files are rustfmt-ed, so format the output the same way before comparing
        let Some(schema_fmt) = rustfmt(dir, &generated.open_map_tiles_schema) else {
            eprintln!("rustfmt not available, skipping");
            return;
        };
        let tables_fmt = rustfmt(dir, &generated.tables).unwrap();
        let schema = std::fs::read_to_string(dir.join("src/generated/open_map_tiles_schema.rs")).unwrap();
        let tables = std::fs::read_to_string(dir.join("src/generated/tables.rs")).unwrap();
        assert!(
            schema == schema_fmt,
            "open_map_tiles_schema.rs is out of date, run `cargo run -p planetiler-openmaptiles --bin generate_openmaptiles`"
        );
        assert!(
            tables == tables_fmt,
            "tables.rs is out of date, run `cargo run -p planetiler-openmaptiles --bin generate_openmaptiles`"
        );
    }

    fn rustfmt(dir: &Path, source: &str) -> Option<String> {
        use std::io::Write;
        use std::process::{Command, Stdio};
        let mut child = Command::new("rustfmt")
            .args(["--edition=2024", "--emit=stdout"])
            .current_dir(dir)
            .stdin(Stdio::piped())
            .stdout(Stdio::piped())
            .stderr(Stdio::null())
            .spawn()
            .ok()?;
        child.stdin.take()?.write_all(source.as_bytes()).ok()?;
        let output = child.wait_with_output().ok()?;
        output.status.success().then(|| String::from_utf8(output.stdout).unwrap())
    }
