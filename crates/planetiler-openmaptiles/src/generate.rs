/// Returns an [`Expression`] that implements the same logic as the
/// [Imposm3 Data Mapping](https://imposm.org/docs/imposm3/latest/mapping.html) definition for a table.
pub fn parse_imposm3_mapping_expression_for_table(table: &Imposm3Table) -> anyhow::Result<Expression> {
    if let Some(type_mappings) = &table.type_mappings {
        let children = type_mappings
            .iter()
            .map(|(k, v)| parse_imposm3_mapping_expression(k, Some(v), table.filters.as_ref()))
            .collect::<anyhow::Result<Vec<_>>>()?;
        Ok(or(children).simplify())
    } else {
        parse_imposm3_mapping_expression(&table.r#type, table.mapping.as_ref(), table.filters.as_ref())
    }
}

/// Returns an [`Expression`] that implements the same logic as the
/// [Imposm3 Data Mapping filters](https://imposm.org/docs/imposm3/latest/mapping.html#filters) for a table.
pub fn parse_imposm3_mapping_expression(
    r#type: &str,
    mapping: Option<&Yaml>,
    filters: Option<&Imposm3Filters>,
) -> anyhow::Result<Expression> {
    let require = match filters.and_then(|f| f.require.as_ref()) {
        Some(r) => parse_field_mapping_expression(r)?,
        None => vec![],
    };
    let reject = match filters.and_then(|f| f.reject.as_ref()) {
        Some(r) => parse_field_mapping_expression(r)?,
        None => vec![],
    };
    let mapping = match mapping {
        Some(m) => parse_field_mapping_expression(m)?,
        None => vec![],
    };
    let type_name = r#type.strip_suffix('s').unwrap_or(r#type);
    Ok(and([or(mapping), and(require), not(or(reject)), expr::try_match_type(type_name)?]).simplify())
}

/// Returns a [`MultiExpression`] to efficiently determine the value for an output vector tile feature (i.e. "class")
/// based on the "field mapping" defined in the layer schema definition.
pub fn generate_field_mapping(values_node: &Yaml) -> anyhow::Result<MultiExpression<String>> {
    let mut mappings = Vec::new();
    for (field, node) in entries(values_node) {
        let expression = or(parse_field_mapping_expression(&node)?).simplify();
        if expression != or([]) && expression != and([]) {
            mappings.push(multi_expression::entry(field, expression));
        }
    }
    Ok(MultiExpression::of(mappings))
}

fn parse_field_mapping_expression(node: &Yaml) -> anyhow::Result<Vec<Expression>> {
    match node {
        Yaml::Mapping(map) => {
            let keys: Vec<String> = map.keys().map(yaml_to_string).collect();
            if keys.iter().any(|k| k == "__AND__") {
                if keys.len() > 1 {
                    bail!("Cannot combine __AND__ with others");
                }
                Ok(vec![and(parse_field_mapping_expression(&map["__AND__"])?)])
            } else if keys.iter().any(|k| k == "__OR__") {
                if keys.len() > 1 {
                    bail!("Cannot combine __OR__ with others");
                }
                Ok(vec![or(parse_field_mapping_expression(&map["__OR__"])?)])
            } else {
                Ok(map
                    .iter()
                    .map(|(k, v)| {
                        let field = yaml_to_string(k);
                        let mut values = Vec::new();
                        to_flat_list(v, &mut values);
                        if values.is_empty() || values.iter().any(|v| v == "__any__") {
                            match_field(&field)
                        } else {
                            match_any(&field, values)
                        }
                    })
                    .collect())
            }
        }
        Yaml::Sequence(items) => {
            let mut result = Vec::new();
            for item in items {
                result.extend(parse_field_mapping_expression(item)?);
            }
            Ok(result)
        }
        Yaml::Null => Ok(vec![]),
        Yaml::Tagged(tagged) => parse_field_mapping_expression(&tagged.value),
        other => bail!("parseExpression input not handled: {other:?}"),
    }
}

/// Appends the textual values in nested arrays of `node` to `out` (non-text values are dropped, like Java's
/// `JsonNode::textValue`).
///
/// For example: `[[[a, b], c], [d]]` becomes `[a, b, c, d]` and `a` becomes `[a]`.
fn to_flat_list(node: &Yaml, out: &mut Vec<String>) {
    match node {
        Yaml::Sequence(items) => items.iter().for_each(|i| to_flat_list(i, out)),
        Yaml::String(s) => out.push(s.clone()),
        _ => {}
    }
}

