/// Normalizes `path` lexically (resolving `.` and `..`), like Java's `Path.normalize`.
fn normalize(path: &Path) -> PathBuf {
    let mut result = PathBuf::new();
    for component in path.components() {
        match component {
            Component::CurDir => {}
            Component::ParentDir => {
                result.pop();
            }
            other => result.push(other),
        }
    }
    result
}

/// The generated files.
#[derive(Debug, Clone)]
pub struct GeneratedCode {
    pub open_map_tiles_schema: String,
    pub tables: String,
}

/// Reads the schema from `schema_dir` (starting from `openmaptiles.yaml`, then each layer file it references, then
/// each imposm3 mapping file those reference) and returns the generated code.
pub fn generate(schema_dir: &Path, tag: &str) -> anyhow::Result<GeneratedCode> {
    let read = |rel: &Path| -> anyhow::Result<Yaml> {
        let path = schema_dir.join(rel);
        tracing::info!("reading {}", path.display());
        let contents = std::fs::read_to_string(&path).with_context(|| format!("reading {}", path.display()))?;
        parse_yaml(&contents).with_context(|| format!("parsing {}", path.display()))
    };
    let tileset = parse_tileset(&read(Path::new("openmaptiles.yaml"))?)?;

    let mut layers = Vec::new();
    let mut mapping_files: Vec<PathBuf> = Vec::new();
    for layer_file in &tileset.layers {
        let layer = parse_layer(&read(Path::new(layer_file))?)?;
        for datasource in &layer.datasources {
            if datasource.r#type == "imposm3" {
                let parent = Path::new(layer_file).parent().unwrap_or(Path::new(""));
                let mapping_path = normalize(&parent.join(&datasource.mapping_file));
                if !mapping_files.contains(&mapping_path) {
                    mapping_files.push(mapping_path);
                }
            } else {
                tracing::warn!("Unknown datasource type: {}", datasource.r#type);
            }
        }
        layers.push(layer);
    }

    // LinkedHashMap.putAll semantics: later definitions replace earlier ones but keep their original position
    let mut tables: Vec<(String, Imposm3Table)> = Vec::new();
    for file in &mapping_files {
        for (name, table) in parse_mapping_tables(&read(file)?)? {
            match tables.iter_mut().find(|(n, _)| *n == name) {
                Some(existing) => existing.1 = table,
                None => tables.push((name, table)),
            }
        }
    }

    Ok(GeneratedCode {
        open_map_tiles_schema: emit_layer_schema_definitions(&tileset, &layers, tag)?,
        tables: emit_table_definitions(&tables, tag)?,
    })
}

