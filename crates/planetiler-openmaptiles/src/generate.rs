//! Port of `Generate.java`: generates the code in the [`generated`](crate::generated) module from the OpenMapTiles
//! schema.
//!
//! The Java version crawls the schema from a tag or branch of the
//! [OpenMapTiles GitHub repo](https://github.com/openmaptiles/openmaptiles). To keep builds offline, the Rust port
//! reads a vendored copy of the schema from `crates/planetiler-openmaptiles/schema` (refresh it with
//! `crates/planetiler-openmaptiles/scripts/fetch-schema.sh <ref> crates/planetiler-openmaptiles/schema`) and the
//! `generate_openmaptiles` binary writes the output to `src/generated`.
//!
//! - `open_map_tiles_schema.rs` contains the output layer definitions (i.e. attributes and allowed values) so that
//!   layer implementations in [`layers`](crate::layers) can reference them instead of hard-coding.
//! - `tables.rs` contains the [imposm3](https://github.com/omniscale/imposm3) table definitions from `mapping.yaml`
//!   files in the OpenMapTiles repo. Layers implement the `*Handler` trait for a table (and return it from the
//!   matching `RowHandlers::as_*_handler` accessor) to "subscribe" to OSM elements that imposm3 would put in that
//!   table.
//!
//! Differences from Java:
//! - Descriptions are emitted as markdown doc comments instead of being rendered to HTML javadoc.
//! - Table rows are lazy views over the source feature (`Option<Cow<str>>`/`bool`/`i64`/`i32` accessors) instead of
//!   eagerly-parsed records, so building a row never allocates.
//! - YAML is parsed with `serde_yaml` (YAML 1.2), so unquoted `yes`/`no` are strings (SnakeYAML treats them as
//!   booleans, which `Generate.java` then drops). The pinned schema quotes them.

