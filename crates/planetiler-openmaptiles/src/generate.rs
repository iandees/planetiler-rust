/// Parses a yaml string, resolving anchors, aliases and merge keys.
pub fn parse_yaml(string: &str) -> anyhow::Result<Yaml> {
    let mut value: Yaml = serde_yaml::from_str(string)?;
    value.apply_merge()?;
    Ok(value)
}

/// Same as [`parse_yaml`] but returns `None` for `None` input (Java `parseYaml(null)`).
pub fn parse_yaml_opt(string: Option<&str>) -> anyhow::Result<Option<Yaml>> {
    string.map(parse_yaml).transpose()
}

fn get<'a>(node: &'a Yaml, key: &str) -> Option<&'a Yaml> {
    node.as_mapping().and_then(|m| m.get(key)).filter(|v| !v.is_null())
}

fn get_str(node: &Yaml, key: &str) -> Option<String> {
    get(node, key).map(yaml_to_string)
}

fn yaml_to_string(node: &Yaml) -> String {
    match node {
        Yaml::String(s) => s.clone(),
        Yaml::Number(n) => n.to_string(),
        Yaml::Bool(b) => b.to_string(),
        Yaml::Null => String::new(),
        other => serde_yaml::to_string(other).unwrap_or_default().trim().to_string(),
    }
}

fn get_string_list(node: &Yaml, key: &str) -> Vec<String> {
    get(node, key).and_then(Yaml::as_sequence).map(|s| s.iter().map(yaml_to_string).collect()).unwrap_or_default()
}

fn entries(node: &Yaml) -> Vec<(String, Yaml)> {
    node.as_mapping().map(|m| m.iter().map(|(k, v)| (yaml_to_string(k), v.clone())).collect()).unwrap_or_default()
}

/// Parses the `tileset` section of `openmaptiles.yaml`.
pub fn parse_tileset(root: &Yaml) -> anyhow::Result<OpenmaptilesTileSet> {
    let tileset = get(root, "tileset").context("missing tileset")?;
    Ok(OpenmaptilesTileSet {
        layers: get_string_list(tileset, "layers"),
        version: get_str(tileset, "version").unwrap_or_default(),
        attribution: get_str(tileset, "attribution").unwrap_or_default(),
        name: get_str(tileset, "name").unwrap_or_default(),
        description: get_str(tileset, "description").unwrap_or_default(),
        languages: get_string_list(tileset, "languages"),
    })
}

/// Parses a `layers/<layer>/<layer>.yaml` file.
pub fn parse_layer(root: &Yaml) -> anyhow::Result<LayerConfig> {
    let layer = get(root, "layer").context("missing layer")?;
    let details = LayerDetails {
        id: get_str(layer, "id").context("missing id")?,
        description: get_str(layer, "description").unwrap_or_default(),
        fields: get(layer, "fields").map(entries).unwrap_or_default(),
        buffer_size: get(layer, "buffer_size").and_then(Yaml::as_f64).unwrap_or(0.0),
    };
    let datasources = get(root, "datasources")
        .and_then(Yaml::as_sequence)
        .map(|s| {
            s.iter()
                .map(|d| Datasource {
                    r#type: get_str(d, "type").unwrap_or_default(),
                    mapping_file: get_str(d, "mapping_file").unwrap_or_default(),
                })
                .collect()
        })
        .unwrap_or_default();
    Ok(LayerConfig { layer: details, datasources })
}

/// Parses an imposm3 table definition.
pub fn parse_table(node: &Yaml) -> anyhow::Result<Imposm3Table> {
    let columns = get(node, "columns")
        .and_then(Yaml::as_sequence)
        .map(|s| {
            s.iter()
                .map(|c| Imposm3Column {
                    r#type: get_str(c, "type").unwrap_or_default(),
                    name: get_str(c, "name").unwrap_or_default(),
                    key: get_str(c, "key"),
                    from_member: get(c, "from_member").and_then(Yaml::as_bool).unwrap_or(false),
                })
                .collect()
        })
        .unwrap_or_default();
    let filters = get(node, "filters")
        .map(|f| Imposm3Filters { reject: get(f, "reject").cloned(), require: get(f, "require").cloned() });
    Ok(Imposm3Table {
        r#type: get_str(node, "type").unwrap_or_default(),
        resolve_wikidata: get(node, "_resolve_wikidata").and_then(Yaml::as_bool).unwrap_or(false),
        columns,
        filters,
        mapping: get(node, "mapping").cloned(),
        type_mappings: get(node, "type_mappings").map(entries),
        relation_types: get_string_list(node, "relation_types"),
    })
}

/// Parses the `tables` section of an imposm3 `mapping.yaml` file.
pub fn parse_mapping_tables(root: &Yaml) -> anyhow::Result<Vec<(String, Imposm3Table)>> {
    get(root, "tables")
        .map(entries)
        .unwrap_or_default()
        .into_iter()
        .map(|(k, v)| Ok((k.clone(), parse_table(&v).with_context(|| format!("table {k}"))?)))
        .collect()
}

